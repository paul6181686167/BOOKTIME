export function catalogMetaForKey(key) {
  if (!key) return {};
  if (SERIES_CATALOG_META[key]) return SERIES_CATALOG_META[key];
  if (ALIASES[key] && SERIES_CATALOG_META[ALIASES[key]]) {
    return SERIES_CATALOG_META[ALIASES[key]];
  }
  return {};
}
